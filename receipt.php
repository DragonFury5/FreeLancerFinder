<?php
require_once __DIR__ . '/config/db.php';
require_once __DIR__ . '/includes/auth.php';
require_once __DIR__ . '/includes/lang.php';
require_once __DIR__ . '/includes/earnings.php';

require_login();

$me = current_user();
$isAdmin = ($me['role'] ?? '') === 'admin';

$receiptId = trim($_GET['id'] ?? '');
if ($receiptId === '') {
    header('Location: earnings.php');
    exit;
}

$stmt = $pdo->prepare(
    "SELECT w.*, u.name AS lancer_name, u.email AS lancer_email
     FROM withdrawals w
     JOIN users u ON u.id = w.lancer_id
     WHERE w.receipt_id = ?"
);
$stmt->execute([$receiptId]);
$w = $stmt->fetch();

if (!$w) {
    http_response_code(404);
    $pageTitle = 'Receipt not found — FLF';
    require __DIR__ . '/includes/header.php';
    echo '<div class="container"><div class="empty" style="padding:100px 20px">'
       . '<strong>Receipt not found.</strong>'
       . '<p><a href="earnings.php">← Back to earnings</a></p></div></div>';
    require __DIR__ . '/includes/footer.php';
    exit;
}

// Access rule: owner or admin only
$isOwner = (int)$w['lancer_id'] === (int)$me['id'];
if (!$isAdmin && !$isOwner) {
    http_response_code(404);
    $pageTitle = 'Receipt not found — FLF';
    require __DIR__ . '/includes/header.php';
    echo '<div class="container"><div class="empty" style="padding:100px 20px">'
       . '<strong>Receipt not found.</strong></div></div>';
    require __DIR__ . '/includes/footer.php';
    exit;
}

function rp_local($n) { return 'Rp ' . number_format((float)$n, 0, ',', '.'); }

$statusClass = [
    'SENT'     => 'sent',
    'PENDING'  => 'pending',
    'REJECTED' => 'rejected',
][$w['status']] ?? 'pending';

$statusLabel = [
    'SENT'     => 'Sent',
    'PENDING'  => 'Pending',
    'REJECTED' => 'Rejected',
][$w['status']] ?? $w['status'];

$pageTitle = $w['receipt_id'] . ' — FLF';
require __DIR__ . '/includes/header.php';
?>

<div class="container">
  <div class="receipt">

    <div class="receipt__brand">
      <span class="brand-mark">F</span>
      <span class="brand-text">FLF<small>FreeLanceFinder</small></span>
    </div>

    <p class="receipt__title">Withdrawal receipt</p>
    <h1 class="receipt__id"><?= e($w['receipt_id']) ?></h1>
    <p class="receipt__date">
      <?= date('F j, Y · H:i', strtotime($w['requested_at'])) ?>
    </p>

    <hr>

    <p class="receipt__section">Status</p>
    <span class="receipt__badge receipt__badge--<?= $statusClass ?>">
      <?= e($statusLabel) ?>
    </span>

    <hr>

    <p class="receipt__section">Lancer</p>
    <dl style="margin:0">
      <div class="receipt__line"><dt>Name</dt>  <dd><?= e($w['lancer_name']) ?></dd></div>
      <div class="receipt__line"><dt>Email</dt> <dd><?= e($w['lancer_email']) ?></dd></div>
    </dl>

    <hr>

    <p class="receipt__section">Payout account</p>
    <dl style="margin:0">
      <div class="receipt__line"><dt>Bank</dt>    <dd><?= e($w['bank']) ?></dd></div>
      <div class="receipt__line"><dt>Account</dt> <dd><?= e(mask_account($w['account'])) ?></dd></div>
      <div class="receipt__line"><dt>Holder</dt>  <dd><?= e($w['account_name']) ?></dd></div>
    </dl>

    <hr>

    <p class="receipt__section">Amount</p>
    <dl style="margin:0">
      <div class="receipt__line">
        <dt>Requested</dt>
        <dd><?= rp_local($w['amount']) ?></dd>
      </div>
      <div class="receipt__line">
        <dt>Fee</dt>
        <dd>
          <?= rp_local($w['fee']) ?>
          <small style="color:var(--muted);font-weight:500">
            · <?= $w['flf_covers_fee'] ? 'paid by FLF' : 'paid by Lancer' ?>
          </small>
        </dd>
      </div>
      <div class="receipt__line receipt__line--total">
        <dt>You received</dt>
        <dd><?= rp_local($w['amount']) ?></dd>
      </div>
    </dl>

    <?php if (!empty($w['tripay_ref'])): ?>
      <hr>
      <p class="receipt__section">Tripay reference</p>
      <div class="receipt__line">
        <dt>Ref</dt>
        <dd style="font-family:ui-monospace,Menlo,Consolas,monospace;font-size:.85rem">
          <?= e($w['tripay_ref']) ?>
        </dd>
      </div>
    <?php endif; ?>

    <?php if (!empty($w['note'])): ?>
      <hr>
      <p class="receipt__section">Note</p>
      <p style="margin:0;color:var(--ink-soft);font-size:.9rem"><?= e($w['note']) ?></p>
    <?php endif; ?>

    <div class="receipt__actions">
      <button class="btn btn-outline" type="button" onclick="window.print()">Print</button>
      <a class="btn btn-primary" href="<?= $isAdmin ? 'admin/receipts.php' : 'earnings.php' ?>">
        <?= $isAdmin ? 'All receipts' : 'Back to earnings' ?>
      </a>
    </div>

    <p class="receipt__foot">
      This receipt was generated by FLF — FreeLanceFinder. Keep it for your records.
    </p>

  </div>
</div>

<?php require __DIR__ . '/includes/footer.php'; ?>